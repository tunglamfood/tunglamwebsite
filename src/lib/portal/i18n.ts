export const PORTAL_DICT: Record<PortalLang, PortalDict> = { en, ms, zh };

export function pfmt(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function money(amount: number, currency = "MYR") {
  const symbol = currency === "SGD" ? "S$" : "RM";
  return `${symbol} ${amount.toLocaleString("en-MY", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}
